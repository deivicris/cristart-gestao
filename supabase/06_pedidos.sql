create table if not exists public.pedidos (
  id                 uuid primary key default gen_random_uuid(),
  numero             int generated by default as identity,
  titulo             text not null,
  cliente_nome       text,
  cliente_whats      text,
  cliente_cidade     text,
  canal              text references public.plataformas(id) on delete set null,
  status             text not null default 'orcamento' check (status in
                       ('orcamento','aprovado','fila','imprimindo','acabamento','pronto','entregue','cancelado')),
  data_pedido        date not null default current_date,
  prazo              date,
  entregue_em        date,
  ordem              int not null default 0,
  valor_combinado    numeric(10,2),          -- preço fechado com o cliente (vazio = soma dos itens)
  sinal              numeric(10,2),
  sinal_recebido     boolean not null default false,
  pagamento          text,
  quitado            boolean not null default false,
  perda_prevista_pct numeric(6,2) not null default 10,  -- margem de perda no orçamento
  observacoes        text,
  licoes             text,
  venda_id           uuid references public.vendas(id) on delete set null,
  criado_por         text default (auth.jwt() ->> 'email'),
  criado_em          timestamptz not null default now(),
  atualizado_em      timestamptz not null default now()
);

create table if not exists public.pedido_itens (
  id               uuid primary key default gen_random_uuid(),
  pedido_id        uuid not null references public.pedidos(id) on delete cascade,
  produto_id       uuid references public.produtos(id) on delete set null,
  descricao        text,
  quantidade       int not null default 1 check (quantidade > 0),
  preco_unit       numeric(10,2),
  material         text,
  gramas_unit      numeric(10,1),
  tempo_min_unit   int,
  personalizacoes  jsonb not null default '[]'::jsonb,   -- [{"t":"Maria","ok":false}, …]
  feitas           int not null default 0,                -- peças prontas (quando não há lista)
  ordem            int not null default 0
);

create table if not exists public.pedido_custos (
  id          uuid primary key default gen_random_uuid(),
  pedido_id   uuid not null references public.pedidos(id) on delete cascade,
  tipo        text not null default 'insumo' check (tipo in ('insumo','frete','outro')),
  insumo_id   uuid references public.insumos(id) on delete set null,
  descricao   text,
  quantidade  numeric(10,2) not null default 1,
  custo_unit  numeric(10,4) not null default 0,
  baixado     boolean not null default false,             -- já saiu do estoque de insumos?
  criado_em   timestamptz not null default now()
);

create table if not exists public.pedido_notas (
  id         uuid primary key default gen_random_uuid(),
  pedido_id  uuid not null references public.pedidos(id) on delete cascade,
  texto      text,
  foto       text,
  autor      text default (auth.jwt() ->> 'email'),
  criado_em  timestamptz not null default now()
);

-- Impressões, perdas e vendas podem pertencer a um pedido
alter table public.impressoes add column if not exists pedido_id uuid references public.pedidos(id) on delete set null;
alter table public.perdas     add column if not exists pedido_id uuid references public.pedidos(id) on delete set null;
alter table public.vendas     add column if not exists pedido_id uuid references public.pedidos(id) on delete set null;
-- Impressão de encomenda não entra no estoque de pronta entrega
alter table public.impressoes add column if not exists soma_estoque boolean not null default true;

create or replace function public.ajusta_por_impressao()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE','DELETE') then
    if old.soma_estoque then update produtos set estoque = estoque - old.quantidade where id = old.produto_id; end if;
    update filamentos set restante_g = greatest(0, restante_g + coalesce(old.gramas,0)) where id = old.filamento_id;
  end if;
  if tg_op in ('INSERT','UPDATE') then
    if new.soma_estoque then update produtos set estoque = estoque + new.quantidade where id = new.produto_id; end if;
    update filamentos set restante_g = greatest(0, restante_g - coalesce(new.gramas,0)) where id = new.filamento_id;
  end if;
  return coalesce(new, old);
end $$;

-- Insumos do pedido: quando marcados como "baixado", saem do estoque
create or replace function public.ajusta_por_custo_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE','DELETE') and old.baixado and old.tipo = 'insumo' then
    update insumos set estoque = estoque + old.quantidade where id = old.insumo_id;
  end if;
  if tg_op in ('INSERT','UPDATE') and new.baixado and new.tipo = 'insumo' then
    update insumos set estoque = greatest(0, estoque - new.quantidade) where id = new.insumo_id;
  end if;
  return coalesce(new, old);
end $$;
drop trigger if exists trg_pedido_custos on public.pedido_custos;
create trigger trg_pedido_custos after insert or update or delete on public.pedido_custos
  for each row execute function public.ajusta_por_custo_pedido();

drop trigger if exists trg_pedidos_upd on public.pedidos;
create trigger trg_pedidos_upd before update on public.pedidos
  for each row execute function public.marca_atualizacao();

